    /**
     * Sets the index of the color preset to modify.
     * @param aColorIndex - Color index to modify.
     */
    public void SetColorPresetIndex(int aColorIndex)
    {
        System.out.print("BladeColorScreen preset color set to ");
        System.out.println(aColorIndex);
        
        mColorPresetIndex = aColorIndex;
               
        Integer lCh1 = Converter.byte2int(
            mTargetSettings.GetBladeColors().get(aColorIndex).mChannel1);
        Integer lCh2 = Converter.byte2int(
            mTargetSettings.GetBladeColors().get(aColorIndex).mChannel2);
        Integer lCh3 = Converter.byte2int(
            mTargetSettings.GetBladeColors().get(aColorIndex).mChannel3);

         this.mChnlSlider1.setValue(lCh1);
         this.mChnlSlider2.setValue(lCh2);
         this.mChnlSlider3.setValue(lCh3);
         
         this.mChnlSlider1Lbl.setText(lCh1.toString());
         this.mChnlSlider2Lbl.setText(lCh2.toString());
         this.mChnlSlider3Lbl.setText(lCh3.toString());
    }
    
