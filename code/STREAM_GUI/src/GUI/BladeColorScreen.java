    private void SendBladeChannelSettings(boolean aTurnOn)
    {
        Integer lValue0 = mChnlSlider1.getValue();
        Integer lValue1 = mChnlSlider2.getValue();
        Integer lValue2 = mChnlSlider3.getValue();
        
        mChnlSlider1Lbl.setText(lValue0.toString());
        mChnlSlider2Lbl.setText(lValue1.toString());
        mChnlSlider3Lbl.setText(lValue2.toString());
        
        if(aTurnOn)
        {
            //Set Channel 0
            tBladeControlSetChannelMsg lSetChnlMsg = new tBladeControlSetChannelMsg();
            lSetChnlMsg.mChannel = 0;
            lSetChnlMsg.mValue = lValue0.byteValue();
            mMessageSndr.SendMessage(lSetChnlMsg);

            //Set Channel 1
            lSetChnlMsg.mChannel = 1;
            lSetChnlMsg.mValue = lValue1.byteValue();
            mMessageSndr.SendMessage(lSetChnlMsg);

            //Set Channel 2
            lSetChnlMsg.mChannel = 2;
            lSetChnlMsg.mValue = lValue2.byteValue();
            mMessageSndr.SendMessage(lSetChnlMsg);

            tBladeControlSetPowerMsg lSetPwrMsg = new tBladeControlSetPowerMsg();
            lSetPwrMsg.mPower = 1;
            mMessageSndr.SendMessage(lSetPwrMsg);
        }
    }
        
