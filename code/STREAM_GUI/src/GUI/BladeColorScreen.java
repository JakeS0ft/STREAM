    private void mOkButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mOkButtonActionPerformed
        //De-select the preiview checkbox
        mPreviewCheckbox.setSelected(false);
        
        //Turn off the blade
        CommandMessages.tBladeControlSetPowerMsg lsPwrOffMsg
                = new CommandMessages.tBladeControlSetPowerMsg();
        lsPwrOffMsg.mPower = 0;
        mMessageSndr.SendMessage(lsPwrOffMsg);
              
        //Snag reference to the blade colors
        ArrayList<Settings.tBladeColor> lColors =
                mTargetSettings.GetBladeColors();
        
        //Snag user input channel values
        Integer lChn1 = (Integer)this.mChnlSlider1.getValue();
        Integer lChn2 = (Integer)this.mChnlSlider2.getValue();
        Integer lChn3 = (Integer)this.mChnlSlider3.getValue();
        
        //Update the color preset with user values
        lColors.get(mColorPresetIndex).mChannel1 = lChn1.byteValue();
        lColors.get(mColorPresetIndex).mChannel2 = lChn2.byteValue();
        lColors.get(mColorPresetIndex).mChannel3 = lChn3.byteValue();
        
        System.out.print("Set color preset [");
        System.out.print(mColorPresetIndex);
        System.out.print("]:");
        System.out.print(lColors.get(mColorPresetIndex).mChannel1);
        System.out.print(",");
        System.out.print(lColors.get(mColorPresetIndex).mChannel2);
        System.out.print(",");
        System.out.print(lColors.get(mColorPresetIndex).mChannel3);
        
        //Save new color presets
        mTargetSettings.SetColorPresets(lColors);
        
        if(null != mBladeConfigScreen)
        {
            mBladeConfigScreen.setBounds(this.getBounds());
            mBladeConfigScreen.setVisible(true);
            mBladeConfigScreen.UpdateDisplay();
            this.setVisible(false);
        }
    }//GEN-LAST:event_mOkButtonActionPerformed

