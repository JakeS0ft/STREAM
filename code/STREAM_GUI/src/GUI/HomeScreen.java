    private void mProfileSelectComboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mProfileSelectComboBoxActionPerformed
        
        if(false == mEnableProfileSwitching)
        {
            //Do nothing
        }
        else
        {
            String lSelectedIdxStr = (String) mProfileSelectComboBox.getSelectedItem();
            System.out.println("Selected profile index STR: " + lSelectedIdxStr);
            Integer lProfileInt = Integer.parseInt(lSelectedIdxStr);
            System.out.println("Selected profile index INT: " + lProfileInt);

            //Build message to send
            CommandMessages.tSwitchProfileMsg lMsg = new CommandMessages.tSwitchProfileMsg();
            lMsg.mProfileIdx = lProfileInt.byteValue();

            //Send message to switch profile
            System.out.println("Sending command to switch to profile " + lSelectedIdxStr);
            mSndr.SendMessage(lMsg);

            try {
                Thread.sleep(100);
            } catch (InterruptedException lEx) {
                //Who cares?
            }
            
            //Reload settings from target
            mSettingsMgr.FetchSettingsFromTarget();
        }
    }//GEN-LAST:event_mProfileSelectComboBoxActionPerformed

