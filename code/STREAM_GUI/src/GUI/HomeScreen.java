    private void PopulateSelectProfileComboBox()
    {
        //Fetch list of options
        int lSelectedProfileIdx = (int)mSettingsMgr.GetSaberInfo().mSelectedProfileIndex;
        Integer lNumProfiles = (int)mSettingsMgr.GetSaberInfo().mNumberOfProfiles;
        
        ArrayList<Integer> lProfileList = new ArrayList();
        
        for(int lIdx = 0; lIdx < lNumProfiles; lIdx++)
        {
            System.out.print("Adding profile option:");
            System.out.println(lIdx);
            lProfileList.add(lIdx);
        }
        
        mProfileSelectComboBox.removeAllItems();
        for(Integer lItem : lProfileList)
        {
            mProfileSelectComboBox.addItem(lItem.toString());
        }

        //Now set the selected item in the combo box to be the current profile
        mProfileSelectComboBox.setSelectedIndex(lSelectedProfileIdx);
    }
    
