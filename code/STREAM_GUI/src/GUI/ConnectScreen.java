    private void mConnectButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mConnectButtonActionPerformed
        mHomeScreen = null;
        System.gc();
        
        mStatusLabel.setText("Connecting...");
        System.out.println("Connecting...");
               
        int lSelectedComPort = mComPortComboBox.getSelectedIndex();
        
        mSerialPort = mPorts[lSelectedComPort];
        
        //Try to open the port
        if(mSerialPort.openPort())
        {
            System.out.println("Port opened successfully.");
            
            //Set connection parameters
            mSerialPort.setComPortParameters(9600, 8, 1, SerialPort.NO_PARITY);
            mSerialPort.setComPortTimeouts(SerialPort.TIMEOUT_READ_BLOCKING, 0, 0);
            mSerialPort.setComPortTimeouts(SerialPort.TIMEOUT_WRITE_BLOCKING, 0, 0);
        
            //Clear any garbage off the serial port
            while(mSerialPort.bytesAvailable() > 0)
            {
                byte[] lGarbageByte = new byte[1];
                mSerialPort.readBytes(lGarbageByte, 1);
            }
            
            //Create message receiver
            mMessageRcvr = new ResponseMessageReceiver(mSerialPort);
            mMessageRcvr.Subscribe(this);
            new Thread(mMessageRcvr).start();
            
            //Create message sender
            mMessageSndr = new CommandMessageSender(mSerialPort);
            mStatusLabel.setText("Connected.");
            System.out.println("Connected.");
            
            try
            {
                Thread.sleep(2000);
            }
            catch(InterruptedException lEx)
            {
                lEx.printStackTrace();
            }
            
            for(int lTry = 0; lTry < 120 & mAckCount < 3; lTry++)
            {
                Integer lMsgId = CommandMessages.MessageIds.eeCmdRequestAck.ordinal();
                mMessageSndr.SendOneByteMessage(lMsgId.byteValue());
                
                try
                {
                    Thread.sleep(500);
                }
                catch(InterruptedException lEx)
                {
                    lEx.printStackTrace();
                }
            }
            
            if(mAckCount < 3)
            {
                mStatusLabel.setText("Handshake failed.");
                System.out.println("Handshake failed.");
                this.mMessageRcvr.Stop();
                this.mMessageRcvr = null;
                this.mMessageSndr = null;
                this.mSerialPort.closePort();
                this.mSerialPort = null;
                this.mAckCount = 0;
                this.mTargetSettings = null;
                System.gc();
                
                return; //Quit, we can't start a session
            }
            
            //Create target settings manager
            mTargetSettings = new TargetSettingsManager(mMessageSndr, mMessageRcvr);
            mTargetSettings.Init();
            
            //Try to fetch protocol and version data from the target
            mTargetSettings.FetchProtocolVersionFromTarget();
            if(null == mTargetSettings.GetProtocolVersion())
            {
                System.err.println("Protocol version invalid.");
                mStatusLabel.setText("Protocol version invalid.");
                return; //We can't connect without knowing protocol version
            }
            else if(!Constants.PROTOCOLVERSION.equalsIgnoreCase(mTargetSettings.GetProtocolVersion()))
            {
                System.err.println("Protocol version mismatch.");
                String lStatusText = "Protocol version mismatch! Expected: ";
                lStatusText += Constants.PROTOCOLVERSION.toString();
                lStatusText += " Target is using: ";
                lStatusText += mTargetSettings.GetProtocolVersion().toString();
                
                mStatusLabel.setText(lStatusText);
                return; //Punt on protocol version mismatch
            }
            
            mTargetSettings.FetchFirmwareVersionFromTarget();
            if(null == mTargetSettings.GetFirmwareVersion())
            {
                System.err.println("Firmware version invalid.");
                mStatusLabel.setText("Firmware version invalid.");
                return; //We can't connect without knowing firmware version                
            }
            
            //Create and open the home screen
            Point lLocation = this.getLocation();
            if(null == mHomeScreen)
            {
                mHomeScreen = new HomeScreen(this,
                                             mTargetSettings,
                                             mMessageRcvr,
                                             mMessageSndr);
            }
            java.awt.EventQueue.invokeLater(new Runnable() {
                public void run() {
                    mHomeScreen.setLocation(lLocation);
                    mHomeScreen.setVisible(true);
                }
            });
            
            this.setVisible(false);
            mStatusLabel.setText("");
        }
	else
        {
            mStatusLabel.setText("Unable to open the COM port.");
            System.out.println("Unable to open the COM port.");
            
            JOptionPane.showMessageDialog(this,
                                          "Connection failed.",
                                          "Connect Failure",
                                          JOptionPane.ERROR_MESSAGE);
	}
    }//GEN-LAST:event_mConnectButtonActionPerformed

