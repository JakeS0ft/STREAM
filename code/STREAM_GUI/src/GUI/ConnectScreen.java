    public void Disconnect()
    {
        if(null != mMessageRcvr)
        {
            mMessageRcvr.Stop();
            mMessageRcvr = null;
        }
        
        if(null != mMessageSndr)
        {
            mMessageSndr = null;
        }
        
        if(null != mSerialPort)
        {
            mSerialPort.closePort();
            mSerialPort = null;
        }
        
        mAckCount = 0;
        
        System.gc();
        
        System.out.println("Disconnected.");
    }
    
