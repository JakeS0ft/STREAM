    @Override
    public void NotifyMessage(ResponseMessageBase aMsg)
    {
        if(ResponseMessages.MessageIds.eeAck.ordinal() == aMsg.mMsgId)
        {
            System.out.println("Ack got to subscriber.");
            
            mAckCounter++;
            mAckCountLabel.setText("Ack Count:" + mAckCounter.toString());
        }
        else if(ResponseMessages.MessageIds.eeFirmwareVersionData.ordinal() == aMsg.mMsgId)
        {
            tFirmwareVersionDataMsg lMsg = (tFirmwareVersionDataMsg)aMsg;
            
            Integer lVerMajor = (int)lMsg.mVersionMajor;
            Integer lVerMinor = (int)lMsg.mVersionMinor;
            
            //Update display with the answer
            mFirmwareVersionTextBox.setText(lVerMajor.toString() + "." + lVerMinor.toString());
        }
        else if(ResponseMessages.MessageIds.eeProtocolVersionData.ordinal() == aMsg.mMsgId)
        {
            tProtocolVersionDataMsg lMsg = (tProtocolVersionDataMsg)aMsg;
            
            Integer lVerMajor = (int)lMsg.mVersionMajor;
            Integer lVerMinor = (int)lMsg.mVersionMinor;
            
            mProtocolVersionTextBox.setText(lVerMajor.toString() + "." + lVerMinor.toString());
        }
        
    }
