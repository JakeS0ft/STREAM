    private void mExecutePwrUpDownTestButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_mExecutePwrUpDownTestButtonActionPerformed
        Integer lChnl = mChnlSlider1.getValue();
        lChnl += mChnlSlider2.getValue();
        lChnl += mChnlSlider3.getValue();
        
        if(lChnl.equals(0))
        {
            JOptionPane.showMessageDialog
                (this,
                 "Blade channels are set to zero. The blade won't turn on! \n Use the sliders to set blade color and brightness first.",
                 "Error: Blade channels zero",
                 JOptionPane.ERROR_MESSAGE);
            
            return;
        }

        //Set blade channels per user controls, but don't turn the blade on
        SendBladeChannelSettings(false);
        
        //Create the command message to start the test
        CommandMessages.tPowerUpPowerDownTestMsg lMsg =
                new CommandMessages.tPowerUpPowerDownTestMsg();
        
        Integer lPowerUpTime = (Integer)mPowerUpTimeSpinner.getValue();
        Integer lPowerDownTime = (Integer)mPowerDownTimeSpinner.getValue();
        Integer lStayOnDuration = (Integer)mStayOnTimeSpinner.getValue();
        Integer lFlickerEffect = (Integer)mFlickerEffectSpinner.getValue();
        
        lMsg.mPowerupTime = lPowerUpTime.shortValue();
        lMsg.mPowerdownTime = lPowerDownTime.shortValue();
        lMsg.mOnDuration = lStayOnDuration.byteValue();
        lMsg.mFlickerType = lFlickerEffect.byteValue();
        
        //Send the command to begin the test
        mMessageSndr.SendMessage(lMsg);
        
//        mExecutePwrUpDownTestButton.setEnabled(false);
        Sleep(lStayOnDuration*1000 + lPowerDownTime + lPowerUpTime);
//        mExecutePwrUpDownTestButton.setEnabled(true);
       
    }//GEN-LAST:event_mExecutePwrUpDownTestButtonActionPerformed

